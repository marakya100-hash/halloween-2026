// Session-only shuffled decks: no names or predictions go into storage or a network request.
export function createOracle(random = Math.random) {
  const bags = new Map();
  const last = new Map();
  function draw(key, list) {
    let bag = bags.get(key);
    if (!bag?.length) {
      bag = [...list];
      for (let i=bag.length-1;i>0;i--) { const j=Math.floor(random()*(i+1)); [bag[i],bag[j]]=[bag[j],bag[i]]; }
      if (bag.length>1 && bag[bag.length-1]===last.get(key)) [bag[0],bag[bag.length-1]]=[bag[bag.length-1],bag[0]];
      bags.set(key,bag);
    }
    const text=bag.pop(); last.set(key,text); return text;
  }
  return index => {
    const category=categories[index];
    if (!category) throw new RangeError('Unknown card');
    const rare=random()<0.05;
    const list=rare ? greatProphecies.filter(p=>p[0]===category.id).map(p=>p[1]) : category.predictions;
    return {category, rare, text:draw(category.id+(rare?'-rare':''),list)};
  };
}
